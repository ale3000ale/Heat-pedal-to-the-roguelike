function isWhitespace(character: string | undefined): boolean {
	return whitespace.has(character?.codePointAt(0) ?? -1);
}

/**
 * Riproduce strip().casefold() del backend Python con dati Unicode 15.0.
 * @param name Nome originale, che non viene modificato.
 * @returns Identita' per confronto, senza NFC o rimozione degli accenti.
 */
export function adminCardIdentity(name: string): string {
	const characters = Array.from(name);
	let first = 0;
	let last = characters.length;
	while (first < last && isWhitespace(characters[first])) first += 1;
	while (last > first && isWhitespace(characters[last - 1])) last -= 1;
	return characters
		.slice(first, last)
		.map((character) => folding.get(character.codePointAt(0) ?? -1) ?? character)
		.join('');
}
