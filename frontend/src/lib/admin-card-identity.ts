const folding = new Map<number, string>();
for (const entry of ranges.split(';')) {
	const [start = 0, end = 0, step = 1, delta = 0] = entry.split(',').map(Number);
	for (let code = start; code <= end; code += step) {
		folding.set(code, String.fromCodePoint(code + delta));
	}
}
for (const entry of expansions.split('|')) {
	const [source = '', target = ''] = entry.split('=');
	folding.set(source.codePointAt(0) ?? -1, target);
}

